public enum ActorType {
    /** A partner system, authenticated with the client credentials grant. */
    CLIENT,
    /** A person, for example an auditor. */
    USER,
    /** The gateway itself, for example Camel lifecycle events. */
    SYSTEM,
    /** A caller without valid credentials. */
    ANONYMOUS
}
